/** The run tree: bought with ink, wiped by every reset except for tool unlocks. */

export type Branch = 'core' | 'demo' | 'prec' | 'swarm' | 'alch' | 'cross';
export const BR: Record<Branch, string> = {
  core: 'Core',
  demo: 'Demolition',
  prec: 'Precision',
  swarm: 'Swarm',
  alch: 'Alchemy',
  cross: 'Hybrid',
};
export const BR_COLOR: Record<Branch, string> = {
  core: '#d8d0ff',
  demo: '#ff4d5e',
  prec: '#ffcc33',
  swarm: '#4fe07a',
  alch: '#3ab8ff',
  cross: '#c86bff',
};

/** How much one level multiplies, shared by the stats and the tree's text. */
export const PER = { pick: 1.3, press: 1.15, overclock: 1.12, payload: 1.45, focus: 1.3, rigpower: 1.4, jaws: 1.4, sear: 0.72 };

/** [base, growth]: level l costs ceil(base * growth^l). */
export type CostSpec = [number, number?];
export type Req = [string, number, boolean?];

export interface RunNode {
  id: string;
  br: Branch;
  x: number;
  y: number;
  max: number;
  name: string;
  icon: string;
  cost: Partial<Record<Cur, CostSpec>>;
  req: Req[];
  about: string;
  eff?: (l: number) => string;
  /** Hotbar index this node unlocks. */
  tool?: number;
  auto?: boolean;
  key?: boolean;
}

