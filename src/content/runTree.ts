export function nodeCost(spec: Partial<Record<Cur, CostSpec>>, l: number): Partial<Record<Cur, number>> {
  const c: Partial<Record<Cur, number>> = {};
  for (const k in spec) {
    const [b, g] = spec[k as Cur]!;
    c[k as Cur] = Math.ceil(b * (g || 1) ** l);
  }
  return c;
}
